# services.classify_damage_stage() 의 한국어 출력 → 위 영문 key
KO_TO_KEY = {
    "접촉초기": "initial",
    "개인정보제공": "info_given",
    "링크클릭앱설치": "app_installed",
    "입금송금": "transferred",
}


def resolve(stage: str) -> str:
    """한국어 stage('접촉초기' 등)나 영문 key('initial' 등) 둘 다 받아 템플릿 문자열을 돌려준다.

    알 수 없는 값이면 가장 보수적인 'initial'(접촉초기)로 폴백한다.
    """
    key = KO_TO_KEY.get(stage, stage)
    return GUIDE_TEMPLATES.get(key, GUIDE_TEMPLATES["initial"])
