# 4) 대응 도구 3종
# 플로우차트 노드 → "전화 대본 만들기" / "피해 상황 요약 리포트 만들기" /
#                    "증거 보존 체크리스트 제공"
# 이 세 개는 4가지 가이드 중 어느 것이 나왔든 공통으로 이어지는 다음 단계입니다.
